const DAY = 86_400_000;

type Seed = Partial<Goal> &
  Pick<Goal, 'id' | 'ownerId' | 'title' | 'emoji' | 'story' | 'category' | 'status' | 'tags'> & {
    scene: Scene;
    ago: number; // days since created
  };

function G(s: Seed, now: number): Goal {
  const owner = SEED_PEOPLE[s.ownerId];
  const { ago, ...rest } = s;
  return {
    hood: owner.hood,
    city: owner.city,
    privacy: 'public',
    needs: [],
    baseHelpers: 0,
    shares: 0,
    ...rest,
    scene: { ...rest.scene, motif: MOTIFS[s.id] },
    photo: PHOTOS[s.id],
    createdAt: now - ago * DAY,
  } as Goal;
}

